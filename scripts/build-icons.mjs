// Extracts the fantasy icons the UI uses from @iconify-json/game-icons (CC BY 3.0) into a small
// committed module, so the build never ships the whole 4,000-icon set or loads icons from a CDN.
// Run: npm run icons:build
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const set = JSON.parse(readFileSync(resolve(root, 'node_modules/@iconify-json/game-icons/icons.json'), 'utf8'));
const info = JSON.parse(readFileSync(resolve(root, 'node_modules/@iconify-json/game-icons/info.json'), 'utf8'));

/** Semantic name used by the app → game-icons.net icon id. */
const PICK = {
  // schools of magic
  abjuration: 'magic-shield', conjuration: 'magic-portal', divination: 'crystal-ball', enchantment: 'magic-palm',
  evocation: 'fire-wave', illusion: 'magic-hat', necromancy: 'burning-skull', transmutation: 'crystal-growth',
  // damage types
  acid: 'acid', bludgeoning: 'flanged-mace', cold: 'snowflake-2', fire: 'fire', force: 'laser-burst', lightning: 'lightning-arc',
  necrotic: 'broken-skull', piercing: 'arrowhead', poison: 'poison-bottle', psychic: 'psychic-waves', radiant: 'heraldic-sun',
  slashing: 'claw-slashes', thunder: 'sound-waves',
  // weapon attacks
  pierce: 'plain-dagger', slash: 'broadsword', bludgeon: 'spiked-mace',
  // general
  heal: 'healing', buff: 'sparkles', move: 'boot-prints', reaction: 'bolt-shield', feature: 'book-aura', monster: 'dragon-head',
  multiattack: 'crossed-swords', legendary: 'dragon-orb', action: 'fist', dice: 'dice-fire', rules: 'book-cover', map: 'treasure-map',
  turn: 'hourglass', journal: 'scroll-quill', session: 'campfire',
};

const missing = Object.values(PICK).filter((id) => !set.icons[id]);
if (missing.length) throw new Error(`Icons not in set: ${missing.join(', ')}`);
const size = set.width ?? 512;
const entries = Object.entries(PICK).map(([name, id]) => `  ${JSON.stringify(name)}: ${JSON.stringify(set.icons[id].body)},`).join('\n');
const out = `// GENERATED by scripts/build-icons.mjs from @iconify-json/game-icons — do not edit by hand.
// Icons: game-icons.net, ${info.license.title} (${info.license.url}).
import type { SVGProps } from 'react';

const bodies = {
${entries}
} as const;

export type FantasyIconName = keyof typeof bodies;
export const FANTASY_ICON_SOURCE = { site: 'game-icons.net', license: ${JSON.stringify(info.license.title)}, url: ${JSON.stringify(info.license.url)} } as const;
/** Set-level attribution: the Iconify export does not carry per-icon authors. */
export const FANTASY_ICON_CREDITS: Array<{ name: FantasyIconName; id: string; author: string }> = ${JSON.stringify(
  Object.entries(PICK).map(([name, id]) => ({ name, id, author: 'game-icons.net contributors (Lorc, Delapouite and others)' })),
)};

export function FantasyIcon({ name, title, ...rest }: { name: FantasyIconName; title?: string } & SVGProps<SVGSVGElement>) {
  return (
    <svg viewBox="0 0 ${size} ${size}" width="1em" height="1em" fill="currentColor" aria-hidden={title ? undefined : true} role={title ? 'img' : undefined} {...rest}>
      {title ? <title>{title}</title> : null}
      <g dangerouslySetInnerHTML={{ __html: bodies[name] }} />
    </svg>
  );
}
`;
writeFileSync(resolve(root, 'apps/web/src/app/fantasy-icons.tsx'), out);
console.log(`wrote ${Object.keys(PICK).length} icons`);
